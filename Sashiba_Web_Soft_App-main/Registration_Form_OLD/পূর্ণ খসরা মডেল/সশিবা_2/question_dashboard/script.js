// ==================== ৪. জেনারেট লজিক (সাফল ও মাল্টি-পেজ) শুরু ====================
function generate() {
  sync();
  const checks = document.querySelectorAll(".q-check:checked");
  if (checks.length === 0)
    return alert("দয়া করে অন্তত একটি প্রশ্নের ধরন সিলেক্ট করুন!");

  let qHtml = "";
  let aHtml = "";
  let total = 0;

  checks.forEach((c, idx) => {
    const row = c.closest(".q-item-styled");
    const count = parseInt(row.querySelector(".q-count").value);
    const mark = parseInt(row.querySelector(".q-mark").value);
    const type = c.parentElement.innerText.trim();

    total += count * mark;
    qHtml += `<div style="margin-top:20px;"><strong>${idx + 1}. ${type} (মান: ${mark})</strong><ol style="margin-left:30px; margin-top:10px;">`;

    for (let i = 1; i <= count; i++) {
      qHtml += `<li style="margin-bottom:8px;">এখানে ${type}-এর ${i} নং নমুনা প্রশ্নটি প্রদর্শিত হবে যা ডাটাবেস থেকে নেওয়া।</li>`;
      if (document.getElementById("ansSheet").checked) {
        aHtml += `<div style="margin-bottom:15px; border-left:4px solid var(--primary); padding-left:15px;">
                    <b>${type} প্রশ্ন ${i}:</b> উত্তর এখানে। <br>
                    <small style="color:green">AI ব্যাখ্যা: এই উত্তরটি সঠিক কারণ এটি পাঠ্যবইয়ের লজিক মেনে চলে।</small>
                  </div>`;
      }
    }
    qHtml += `</ol></div>`;
  });

  document.getElementById("qContent").innerHTML = qHtml;
  document.getElementById("aContent").innerHTML = aHtml;
  document.getElementById("v-total").innerText = total;
  alert("আপনার প্রফেশনাল প্রশ্ন ও উত্তরপত্র জেনারেট হয়েছে!");
}
