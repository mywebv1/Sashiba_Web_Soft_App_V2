// ==================== ৩. রিয়েল-টাইম সিঙ্ক ও প্রিভিউ শুরু ====================
function sync() {
  document.getElementById("v-name").innerText =
    document.getElementById("instName").value || "প্রতিষ্ঠানের নাম";
  document.getElementById("v-addr").innerText =
    document.getElementById("instAddr").value || "ঠিকানা এখানে আসবে";
  document.getElementById("v-class").innerText =
    document.getElementById("classSelect").value;
  document.getElementById("v-sub").innerText =
    document.getElementById("subjectSelect").value;
  document.getElementById("v-time").innerText =
    document.getElementById("examTime").value + " মিনিট";

  if (document.getElementById("ansSheet").checked) {
    document.getElementById("ansPage").style.display = "block";
  } else {
    document.getElementById("ansPage").style.display = "none";
  }
}
