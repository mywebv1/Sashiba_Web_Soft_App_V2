// ==================== ২. ইনিশিয়াল লোড ও ড্রপডাউন শুরু ====================
window.onload = () => {
  const clsSel = document.getElementById("classSelect");
  db.classes.forEach((c) => (clsSel.innerHTML += `<option>${c}</option>`));

  loadSubjects();

  const qList = document.getElementById("qConfigList");
  db.qTypes.forEach((t) => {
    qList.innerHTML += `
      <div class="q-item-styled" style="display:grid; grid-template-columns: 2fr 1fr 1fr; gap:10px; margin-bottom:10px; align-items:center;">
        <label class="sq-check"><input type="checkbox" class="q-check" checked><span></span> ${t.name}</label>
        <input type="number" class="q-count" value="${t.count}">
        <input type="number" class="q-mark" value="${t.mark}">
      </div>`;
  });
};

function loadSubjects() {
  const cls = document.getElementById("classSelect").value;
  const subSel = document.getElementById("subjectSelect");

  subSel.innerHTML = "";

  (db.subjects[cls] || []).forEach((s) => {
    subSel.innerHTML += `<option>${s}</option>`;
  });

  loadChapters();

  sync();
}
function loadChapters() {
  const selectedClass = document.getElementById("classSelect").value;
  const selectedSubject = document.getElementById("subjectSelect").value;

  // শ্রেণি + বিষয় মিলিয়ে Key তৈরি
  const key = `${selectedClass}|${selectedSubject}`;

  const chapBox = document.getElementById("chapterContainer");
  chapBox.innerHTML = "";

  (db.chapters[key] || []).forEach((ch) => {
    chapBox.innerHTML += `
      <label class="sq-check">
        <input
          type="checkbox"
          onchange="loadTopics(this,'${ch}')">
        <span></span>
        ${ch}
      </label>
    `;
  });

  // বিষয় পরিবর্তন করলে আগের টপিকগুলো মুছে যাবে
  document.getElementById("topicContainer").innerHTML = "";
}

function loadTopics(checkbox, chapter) {
  const topicBox = document.getElementById("topicContainer");
  if (checkbox.checked) {
    let html = `<div id="topics-for-${chapter}" style="padding:10px; background:#fff; border-radius:8px; margin-top:5px; border:1px dashed #ccc;">
                <strong>${chapter} এর টপিক:</strong><br>`;
    db.topics[chapter].forEach((tp) => {
      html += `<label class="sq-check small"><input type="checkbox" checked><span></span> ${tp}</label>`;
    });
    topicBox.innerHTML += html + `</div>`;
  } else {
    const el = document.getElementById(`topics-for-${chapter}`);
    if (el) el.remove();
  }
}
